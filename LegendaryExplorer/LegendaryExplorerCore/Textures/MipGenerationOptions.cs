namespace LegendaryExplorerCore.Textures
{
    /// <summary>
    /// The filter used to build each lower mip of a generated mip chain.
    /// </summary>
    public enum MipFilter
    {
        /// <summary>
        /// Repeated 2x2 average of the level above, on straight (non-premultiplied) RGBA. Cheap, and what mip
        /// generation has always done. Soft, and fringes the edges of cut-out art (see <see cref="Lanczos3"/>).
        /// </summary>
        Box,

        /// <summary>
        /// Lanczos-3 downscale of the TOP mip straight to each level, computed in premultiplied alpha so that fully
        /// transparent texels (usually black) do not darken the colour of the edges they touch.
        /// </summary>
        Lanczos3
    }

    /// <summary>
    /// Controls how lower mips are generated by <see cref="Image.correctMips"/> and, through it, by texture replacement.
    /// A null or default instance reproduces the historical box-filtered chain exactly.
    /// </summary>
    public sealed class MipGenerationOptions
    {
        /// <summary>The filter used to build each lower mip.</summary>
        public MipFilter Filter { get; init; } = MipFilter.Box;

        /// <summary>
        /// Strength of an unsharp mask applied to every generated level that is at least 4x4 (0 disables it).
        /// Trilinear sampling softens a texture by about half a mip, so a downscale that is exact for the
        /// pixel grid still looks soft on screen; roughly 0.5 - 1.0 compensates for that. The mask works in premultiplied
        /// colour and never lets a colour exceed its alpha, so it cannot add halos to transparent areas.
        /// </summary>
        public float SharpenAmount { get; init; }

        /// <summary>Gaussian radius of the unsharp mask, in texels of the level being sharpened.</summary>
        public float SharpenRadius { get; init; } = 0.8f;

        /// <summary>
        /// Copies the colour of neighbouring visible texels into fully transparent texels (alpha &lt;= 2), a few texels
        /// deep, in every generated level and in the source used to build them. This changes nothing that is drawn directly,
        /// but the game filters straight (non-premultiplied) RGB, so without it the black under a zero-alpha
        /// texel is mixed into every silhouette edge once the texture is minified or magnified. The top mip is only
        /// rewritten when it has to be converted to another format anyway.
        /// </summary>
        public bool PadTransparentColor { get; init; }

        /// <summary>The historical behaviour: box filter, no sharpening, no padding.</summary>
        public static MipGenerationOptions Default => new();

        /// <summary>
        /// A good starting point for cut-out art shown through Scaleform (weapon pictures, icons): Lanczos-3,
        /// a mild unsharp mask and padded transparent colour.
        /// </summary>
        public static MipGenerationOptions HighQuality => new()
        {
            Filter = MipFilter.Lanczos3,
            SharpenAmount = 0.7f,
            PadTransparentColor = true
        };

        internal bool IsDefault => Filter == MipFilter.Box && SharpenAmount <= 0f && !PadTransparentColor;
    }
}
